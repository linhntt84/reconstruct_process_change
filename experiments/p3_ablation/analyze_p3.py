#!/usr/bin/env python3
"""P3 ablations, step 5: paired comparison of every variant with P2 run 1 of glm-5.3-flash (no API calls).

For each experiment and evaluation set, on the case ids shared with P2:
  drift sets: mean O / MR / PI (Ostovar, E4a) or O / O_main (CDLG), and the r5a role scores (PI, RTU) for CDLG;
  paired counts on PI == 1 (P2 only / variant only) with an exact two-sided McNemar p-value;
  null sets: share "insufficient" and number of "supported" claims.
E5-MP (e5_no_time, e5_no_cf on E4a type M): the joint M score needs both perspectives, so it is 0 by
construction once one is removed; the control-flow part and the time part are scored separately here:
  CF part:   O_cf = object score of central | secondary on cf_required (optional: cf_optional plus the time
             target and its predecessors, which belong to the other perspective),
             PI_cf = 1 exact pattern, 0.5 same family, 0 otherwise, capped by O_cf;
  time part: time_detected = target in time_activities | central, time_ok = detected and direction correct.
E8: label replacements and leftovers from run_p3.py map-labels.
Output: results/p3_ablation/p3_paired.md and p3_paired.csv.
"""
from __future__ import annotations

import csv
import json
import math
import sys
from pathlib import Path
from statistics import mean

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]
sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "experiments" / "p0_llm_calibration"))
from score import PATTERN_FAMILY, object_score  # noqa: E402

P2 = ROOT / "results" / "p2_main"
P3 = ROOT / "results" / "p3_ablation"
MAIN = "INTERPRET_EVIDENCE_V2_EN_R3_MP_CONC"
MODEL = "glm-5.3-flash"
EXPS = ["e3_noselect", "e3b_v2en", "e5_no_occ", "e5_no_dir", "e5_no_pos", "e5_no_rel", "e5_no_lag",
        "e5_no_time", "e5_no_cf", "e8_labels", "e9_shuffle"]


def prompt_of(exp: str) -> str:
    return "INTERPRET_EVIDENCE_V2_EN" if exp == "e3b_v2en" else MAIN


def read_csv(path: Path) -> dict:
    if not path.exists():
        return {}
    with path.open(encoding="utf-8") as handle:
        return {r["case_id"]: r for r in csv.DictReader(handle)}


def num(x):
    try:
        v = float(x)
        return None if math.isnan(v) else v
    except (TypeError, ValueError):
        return None


def mcnemar(b: int, c: int) -> float:
    n = b + c
    if n == 0:
        return 1.0
    k = min(b, c)
    return min(1.0, 2 * sum(math.comb(n, i) for i in range(k + 1)) / 2 ** n)


def extractions(base: Path, prompt: str) -> dict:
    folder = base / "extractions_r5" / prompt / MODEL / "run1"
    return {p.stem: json.loads(p.read_text(encoding="utf-8"))["extraction"] for p in folder.glob("*.json")}


def mp_parts(e: dict, case: dict, lm: dict) -> dict:
    central, secondary = set(e["central_activities"]), set(e.get("secondary_activities", []))
    time_acts = set(e.get("time_activities", []))
    cf_req = {lm[a] for a in json.loads(case["cf_required"]) if a in lm}
    cf_opt = {lm[a] for a in json.loads(case["cf_optional"]) if a in lm}
    x = lm[case["time_target"]]
    preds = {lm[a] for a in json.loads(case["time_predecessors"]) if a in lm}
    # the time target and its predecessors are legitimate objects of the other perspective: neutral here
    o_cf = object_score(central | secondary, cf_req, cf_opt | {x} | preds)
    truth, pred = PATTERN_FAMILY[case["cf_pattern"]], PATTERN_FAMILY.get(e.get("pattern", ""), "")
    pi_raw = 1.0 if e.get("pattern") == case["cf_pattern"] else 0.5 if pred == truth else 0.0
    detected = x in time_acts | central
    return {"O_cf": o_cf, "PI_cf": min(o_cf, pi_raw), "time_detected": float(detected),
            "time_ok": float(detected and e.get("time_direction") == case["time_direction"])}


def main():
    sys.path.insert(0, str(ROOT / "experiments" / "p2_main"))
    from score_p2 import e4_cases
    e4 = e4_cases()
    ref = read_csv(P2 / f"scores_{MAIN}_{MODEL}_run1.csv")
    ref_roles = read_csv(P2 / f"scores_cdlg_roles_{MAIN}_{MODEL}_run1.csv")
    rows, md = [], ["# P3: paired comparison with P2 run 1 (glm-5.3-flash)", "",
                    "Generated by experiments/p3_ablation/analyze_p3.py. McNemar: exact two-sided test on "
                    "PI == 1 (b = P2 only, c = variant only).", ""]
    md += ["## Drift sets", "", "| Exp | Set | n | O P2→var | MR P2→var | PI P2→var | b / c | p |",
           "|---|---|---|---|---|---|---|---|"]
    null_md = ["## Null sets", "", "| Exp | Set | n | Insufficient P2 | Insufficient var | Supported P2 | "
               "Supported var |", "|---|---|---|---|---|---|---|"]
    role_md = ["## CDLG roles (r5a)", "", "| Exp | n | PI P2→var | RTU P2→var | b / c | p |",
               "|---|---|---|---|---|---|"]
    mp_md = ["## E5-MP: E4a type M, parts scored separately", "",
             "| Variant | n | O_cf | PI_cf | time detected | time direction ok | supported / insufficient |",
             "|---|---|---|---|---|---|---|"]
    p2_ex = extractions(P2, MAIN)
    for exp in EXPS:
        var = read_csv(P3 / exp / f"scores_{prompt_of(exp)}_{MODEL}_run1.csv")
        sets = sorted({(r["set"], r["kind"]) for r in var.values()})
        for set_, kind in sets:
            ids = [c for c, r in var.items() if r["set"] == set_ and r["kind"] == kind and c in ref]
            if kind == "null":
                f = lambda d, lvl: sum(d[c]["support_level"] == lvl for c in ids)
                null_md.append(f"| {exp} | {set_} | {len(ids)} | {f(ref, 'insufficient')} | "
                               f"{f(var, 'insufficient')} | {f(ref, 'supported')} | {f(var, 'supported')} |")
                rows.append({"exp": exp, "set": set_, "kind": kind, "n": len(ids),
                             "insufficient_p2": f(ref, "insufficient"), "insufficient_var": f(var, "insufficient")})
                continue
            cells, row = [], {"exp": exp, "set": set_, "kind": kind, "n": len(ids)}
            metrics = ("O", "O_main", "O_F1") if set_ == "cdlg" else ("target_claimed", "target_main") \
                if set_ == "e4b" else ("O", "MR", "PI")
            for m in metrics:
                a = [num(ref[c].get(m)) for c in ids]
                v = [num(var[c].get(m)) for c in ids]
                pairs = [(x, y) for x, y in zip(a, v) if x is not None and y is not None]
                if pairs:
                    ma, mv = mean(p[0] for p in pairs), mean(p[1] for p in pairs)
                    cells.append(f"{m} {ma:.3f}→{mv:.3f}")
                    row[f"{m}_p2"], row[f"{m}_var"] = round(ma, 3), round(mv, 3)
            key = "PI" if "PI" in metrics else metrics[0]
            b = sum(num(ref[c].get(key)) == 1 and num(var[c].get(key)) != 1 for c in ids)
            cc = sum(num(ref[c].get(key)) != 1 and num(var[c].get(key)) == 1 for c in ids)
            row.update({"b": b, "c": cc, "p": round(mcnemar(b, cc), 4)})
            rows.append(row)
            cells += [""] * (3 - len(cells))
            md.append(f"| {exp} | {set_} | {len(ids)} | " + " | ".join(cells) +
                      f" | {b} / {cc} | {mcnemar(b, cc):.3f} |")
        roles = read_csv(P3 / exp / f"scores_cdlg_roles_{prompt_of(exp)}_{MODEL}_run1.csv")
        if roles:
            ids = [c for c in roles if c in ref_roles]
            pa, pv = mean(float(ref_roles[c]["PI"]) for c in ids), mean(float(roles[c]["PI"]) for c in ids)
            ra, rv = mean(float(ref_roles[c]["RTU"]) for c in ids), mean(float(roles[c]["RTU"]) for c in ids)
            b = sum(float(ref_roles[c]["PI"]) == 1 and float(roles[c]["PI"]) != 1 for c in ids)
            cc = sum(float(ref_roles[c]["PI"]) != 1 and float(roles[c]["PI"]) == 1 for c in ids)
            role_md.append(f"| {exp} | {len(ids)} | {pa:.3f}→{pv:.3f} | {ra:.3f}→{rv:.3f} | {b} / {cc} | "
                           f"{mcnemar(b, cc):.3f} |")
            rows.append({"exp": exp, "set": "cdlg_roles", "kind": "drift", "n": len(ids), "PI_p2": round(pa, 3),
                         "PI_var": round(pv, 3), "RTU_p2": round(ra, 3), "RTU_var": round(rv, 3), "b": b, "c": cc,
                         "p": round(mcnemar(b, cc), 4)})
        if exp in ("e5_no_time", "e5_no_cf"):
            vex = extractions(P3 / exp, MAIN)
            for label, source in (("P2 (both)", p2_ex), (exp, vex)):
                parts, levels = [], {"supported": 0, "insufficient": 0}
                for cid in sorted(vex):
                    lm = json.loads((P2 / "audit" / f"{cid}.json").read_text(encoding="utf-8"))["label_map"]
                    parts.append(mp_parts(source[cid], e4[cid], lm))
                    lvl = source[cid]["support_level"]
                    levels[lvl] = levels.get(lvl, 0) + 1
                if label.startswith("P2") and exp == "e5_no_cf":
                    continue
                mp_md.append(f"| {label} | {len(parts)} | " + " | ".join(
                    f"{mean(p[k] for p in parts):.3f}" for k in ("O_cf", "PI_cf", "time_detected", "time_ok")) +
                    f" | {levels.get('supported', 0)} / {levels.get('insufficient', 0)} |")
    e8 = []
    for path in sorted((P3 / "e8_labels" / "runs").glob("*/*/run1/*.json")):
        r = json.loads(path.read_text(encoding="utf-8"))
        if r.get("status") == "success":
            e8.append((sum(r.get("label_replacements", {}).values()), r.get("label_leftovers", [])))
    e8_md = ["## E8: activity names mapped back to codes", "",
             f"{len(e8)} explanations, {sum(n for n, _ in e8)} names replaced (median "
             f"{sorted(n for n, _ in e8)[len(e8) // 2]} per explanation); "
             f"{sum(bool(l) for _, l in e8)} explanations with names left without prefix: "
             f"{sorted({x for _, l in e8 for x in l})}."]
    out = "\n".join(md + [""] + role_md + [""] + null_md + [""] + mp_md + [""] + e8_md) + "\n"
    (P3 / "p3_paired.md").write_text(out, encoding="utf-8")
    fields = list(dict.fromkeys(k for r in rows for k in r))
    with (P3 / "p3_paired.csv").open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=fields)
        writer.writeheader()
        writer.writerows(rows)
    print(out)


if __name__ == "__main__":
    main()
