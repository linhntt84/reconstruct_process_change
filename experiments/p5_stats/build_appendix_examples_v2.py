#!/usr/bin/env python3
"""Appendix A of the revision: four scoring examples from the archived P2 outputs (GLM, run 1). No API calls.

Selection is deterministic: the first case (sorted by case id) that satisfies each condition.
  1. Ostovar Frequency change reconstructed completely (RTU = 1); ProDrift misses all Frequency changes.
  2. Ostovar ParallelMove change with the right activities and mechanism but the serial variant (PI = 0.5).
  3. Ostovar no-change pair concluded as insufficient evidence, with at least one qualified item.
  4. E4a mixed change (control flow + timing) with both parts recovered.
For each: reference, evidence summary, the Inference section verbatim, the blind extraction and the scores.
Writes Latex/IEEE_Access_2026_revision/appendices/A_examples_v2.tex
"""
from __future__ import annotations

import csv
import json
import re
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "experiments" / "p2_main"))
from score_p2 import e4_cases, ostovar_references  # noqa: E402

P2 = ROOT / "results" / "p2_main"
PROMPT, MODEL = "INTERPRET_EVIDENCE_V2_EN_R3_MP_CONC", "glm-5.3-flash"
OUT = ROOT.parent / "Latex" / "IEEE_Access_2026_revision" / "appendices" / "A_examples_v2.tex"


def esc(t: str) -> str:
    t = t.replace("\\", "\\textbackslash{}")
    for a, b in (("&", "\\&"), ("%", "\\%"), ("#", "\\#"), ("_", "\\_"), ("{", "\\{"), ("}", "\\}"),
                 ("$", "\\$"), ("~", "\\textasciitilde{}"), ("^", "\\textasciicircum{}")):
        t = t.replace(a, b)
    t = re.sub(r'"([^"]*)"', r"``\1''", t)
    t = t.replace("→", "$\\rightarrow$").replace("≈", "$\\approx$").replace("≥", "$\\geq$").replace("≤", "$\\leq$")
    t = t.replace("–", "--").replace("—", "---").replace("×", "$\\times$").replace("…", "\\dots{}")
    t = re.sub(r"\*\*([^*]+)\*\*", r"\\textbf{\1}", t)
    return t


SET_NAMES = {"ostovar3": "Ostovar size 3", "ostovar5": "Ostovar size 5", "cdlg": "CDLG",
             "null_ostovar3": "Ostovar size 3, no change", "null_ostovar5": "Ostovar size 5, no change",
             "null_cdlg": "CDLG, no change", "e4a": "Ostovar-Time", "e4b": "BPI17-Resource"}


def set_label(set_name: str) -> str:
    """Paper name of an evaluation set (internal set codes are not shown in the paper)."""
    return SET_NAMES.get(set_name, set_name)


def inference(text: str) -> str:
    part = text.split("### Inference", 1)[1] if "### Inference" in text else text
    lines = [ln.strip() for ln in part.strip().splitlines() if ln.strip()]
    return "\\par\n".join(esc(ln[2:] if ln.startswith("- ") else ln) for ln in lines)


def main():
    scores = {r["case_id"]: r for r in csv.DictReader((P2 / f"scores_{PROMPT}_{MODEL}_run1.csv").open())}
    refs, e4 = ostovar_references(), e4_cases()
    conds = [
        ("A Frequency change reconstructed completely",
         lambda s: s["set"] == "ostovar3" and s["type"] == "Frequency" and s["RTU"] == "1.0"),
        ("A parallel move described as a serial move",
         lambda s: s["set"] == "ostovar3" and s["type"] == "ParallelMove" and s["PI"] == "0.5"
         and s["O"] == "1.0"),
        ("A no-change pair with qualified items",
         lambda s: s["set"] == "null_ostovar3" and s["support_level"] == "insufficient" and int(s["n_evidence"]) > 0),
        ("A mixed control-flow and timing change",
         lambda s: s["set"] == "e4a" and s["type"] == "M" and s["PI"] == "1.0" and s["time_detected"] == "1.0"),
    ]
    tex = ["% Generated by GitHub_Revision/experiments/p5_stats/build_appendix_examples_v2.py; do not edit by hand.",
           "\\section{Scoring Examples}", "\\label{app:verbatim_examples}", "\\begin{revised}", "",
           "The four examples below are taken from the archived GLM outputs (run~1), each being the first case, "
           "by case identifier, that meets the stated condition. For each we give the hidden reference (activity "
           "codes as seen by the model; optional activities in parentheses), the qualified evidence, the "
           "\\emph{Inference} section of the explanation verbatim, the blind extraction and the scores. The full "
           "explanations, evidence documents and extractions are released with the code.", ""]
    for k, (title, cond) in enumerate(conds, 1):
        cid = next(c for c in sorted(scores) if cond(scores[c]))
        s = scores[cid]
        ev = json.loads((P2 / "evidence" / f"{cid}.json").read_text())
        lm = json.loads((P2 / "audit" / f"{cid}.json").read_text())["label_map"]
        text = json.loads((P2 / "runs" / PROMPT / MODEL / "run1" / f"{cid}.json").read_text())["text"]
        ex = json.loads((P2 / "extractions_r5" / PROMPT / MODEL / "run1" / f"{cid}.json").read_text())["extraction"]
        fam = Counter(e["id"].rstrip("0123456789") for e in ev["evidence"])
        fams = ", ".join(f"{f} {n}" for f, n in fam.items()) or "none"
        if s["set"].startswith("null"):
            ref = "no change"
        elif s["set"] == "e4a":
            c = e4[cid]
            req = [lm[a] for a in json.loads(c["required_activities_real"]) if a in lm]
            opt = [lm[a] for a in json.loads(c["optional_activities_real"]) if a in lm]
            ref = (f"{c['cf_pattern']} on {', '.join(sorted(req))}"
                   + (f" ({', '.join(sorted(opt))})" if opt else "")
                   + f"; timing of {lm[c['time_target']]} {'slower' if c['time_direction'] == 'increase' else 'faster'}")
        else:
            pat, req, opt = refs[cid]
            ref = f"{pat} on {', '.join(sorted(lm[a] for a in req if a in lm))}" + (
                f" ({', '.join(sorted(lm[a] for a in opt if a in lm))})" if opt else "")
        extraction = (f"support {ex['support_level']}; main hypothesis "
                      f"{', '.join(ex['central_activities']) or '---'}; mechanism {ex['mechanism'].replace('_', ' ')}; "
                      f"pattern {ex.get('pattern', '---')}")
        if ex.get("secondary_activities"):
            extraction += f"; additional changes {', '.join(ex['secondary_activities'])}"
        if ex.get("time_activities"):
            extraction += f"; timing {', '.join(ex['time_activities'])} ({ex['time_direction']})"
        sc = ("insufficient evidence (correct)" if s["set"].startswith("null") else
              f"$O={s['O']}$, $\\mathrm{{MR}}={s['MR']}$, $\\mathrm{{PI}}={s['PI']}$"
              + (f", RTU $={s['RTU']}$" if s["RTU"] else f", timing detected $={s['time_detected']}$"))
        tex += [f"\\subsection{{Example {k}: {title}}}", f"\\label{{app:grading_example_{k}}}", "",
                "{\\footnotesize\\noindent\\begin{tabularx}{\\columnwidth}{@{}>{\\raggedright\\arraybackslash}"
                "p{0.24\\columnwidth}X@{}}", "\\toprule",
                f"Case & {set_label(s['set'])}, \\texttt{{{cid.split('_', 1)[1]}}} \\\\",
                f"Reference & {esc(ref)} \\\\",
                f"Evidence & {len(ev['evidence'])} item{'s' if len(ev['evidence']) != 1 else ''} ({esc(fams)}); "
                f"{ev['screening']['items_expected_without_change']} expected without change \\\\",
                f"Extraction & {esc(extraction)} \\\\",
                f"Scores & {sc} \\\\", "\\bottomrule", "\\end{tabularx}}", "",
                "\\smallskip\\noindent\\textbf{Inference (verbatim).}\\par\\smallskip",
                "{\\footnotesize\\sloppy", inference(text), "\\par}", "\\bigskip", ""]
        print(k, cid, s["type"], len(ev["evidence"]), ex["pattern"] if "pattern" in ex else "")
    tex += ["\\end{revised}", ""]
    OUT.write_text("\n".join(tex), encoding="utf-8")
    print("->", OUT)


if __name__ == "__main__":
    main()
