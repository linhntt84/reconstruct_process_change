#!/usr/bin/env python3
"""P5: per-case stability of the interpretation across the three runs (R4 #3a). No API calls.

For every case and model: do the three explanations (runs 1-3, same evidence and prompt) yield the same extracted
main-hypothesis activity set, the same pattern, the same support level, and the same score? Extractions: rubric r5
(results/p2_main/extractions_r5/<prompt>/<model>/run<k>/<case>.json); scores: the P2 score files.
Output: results/p5_stats/run_stability.md and .csv.
"""
from __future__ import annotations

import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
P2 = ROOT / "results" / "p2_main"
OUT = ROOT / "results" / "p5_stats"
PROMPT = "INTERPRET_EVIDENCE_V2_EN_R3_MP_CONC"
MODELS = ("glm-5.3-flash", "deepseek-v4-flash")
RUNS = (1, 2, 3)


def scores(model: str, k: int) -> dict:
    with (P2 / f"scores_{PROMPT}_{model}_run{k}.csv").open(encoding="utf-8") as handle:
        return {r["case_id"]: r for r in csv.DictReader(handle)}


def extraction(model: str, k: int, cid: str):
    p = P2 / "extractions_r5" / PROMPT / model / f"run{k}" / f"{cid}.json"
    return json.loads(p.read_text())["extraction"] if p.exists() else None


def main():
    rows, md = [], ["# Per-case stability across the three runs", "",
                    "Generated by experiments/p5_stats/run_stability.py. A case counts as stable for a field when the "
                    "three runs give the same value (extracted with rubric r5). Score stability: same PI (Ostovar, "
                    "E4a) or same O (CDLG) in all three runs.", "",
                    "| Model | Set | n | Same activities | Same pattern | Same support level | Same score | "
                    "All runs correct (PI = 1) | All runs wrong (PI = 0) |",
                    "|---|---|---|---|---|---|---|---|---|"]
    for model in MODELS:
        sc = [scores(model, k) for k in RUNS]
        sets = sorted({(r["set"], r["kind"]) for r in sc[0].values()})
        for set_, kind in sets:
            ids = [c for c, r in sc[0].items() if r["set"] == set_ and r["kind"] == kind and all(c in s for s in sc)]
            stats = {"acts": 0, "pattern": 0, "support": 0, "score": 0, "all1": 0, "all0": 0, "n": 0}
            key = "O" if set_ == "cdlg" else "PI"
            for cid in ids:
                ex = [extraction(model, k, cid) for k in RUNS]
                if any(e is None for e in ex):
                    continue
                stats["n"] += 1
                stats["acts"] += len({frozenset(e["central_activities"]) for e in ex}) == 1
                stats["pattern"] += len({e.get("pattern") for e in ex}) == 1
                stats["support"] += len({e["support_level"] for e in ex}) == 1
                vals = [s[cid].get(key, "") for s in sc]
                stats["score"] += len(set(vals)) == 1
                stats["all1"] += all(v not in ("", "nan") and float(v) == 1.0 for v in vals)
                stats["all0"] += all(v not in ("", "nan") and float(v) == 0.0 for v in vals)
            n = stats["n"]
            if not n:
                continue
            pct = {k: stats[k] / n for k in stats if k != "n"}
            show_score = kind == "drift" and set_ in ("ostovar3", "ostovar5", "cdlg", "e4a")
            md.append(f"| {model} | {set_} {kind} | {n} | {pct['acts']:.2f} | {pct['pattern']:.2f} | "
                      f"{pct['support']:.2f} | " + (f"{pct['score']:.2f} | {pct['all1']:.2f} | {pct['all0']:.2f} |"
                                                    if show_score else "— | — | — |"))
            rows.append({"model": model, "set": set_, "kind": kind, "n": n, **{k: round(v, 3) for k, v in pct.items()}})
    (OUT / "run_stability.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    with (OUT / "run_stability.csv").open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    print("\n".join(md))


if __name__ == "__main__":
    main()
