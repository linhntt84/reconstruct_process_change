#!/usr/bin/env python3
"""P5: exact McNemar tests on the binary outcomes for DeepSeek vs GLM and for every ablation vs the full pipeline (GLM).

Binary outcomes: RTU (Ostovar, CDLG roles), overclaim (Ostovar), 'insufficient' on no-change pairs, time_detected
(E4a), target_claimed and target_main (E4b). Each arm's outcome for a case is the majority over its three runs
(>= 2 of 3), as in method_contrasts.py. b = successes only in the first arm (P2 / GLM), c = only in the second
(variant / DeepSeek); exact two-sided test. No API calls.
Output: results/p5_stats/mcnemar_all.{md,csv}
"""
from __future__ import annotations

import csv
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from aggregate_runs import DS, EXPS, GLM, OUT, RUNS, p2_scores, p3_scores, value  # noqa: E402
from method_contrasts import mcnemar  # noqa: E402

TESTS = [  # (set, kind, roles, metric)
    ("ostovar3", "drift", False, "RTU"), ("ostovar5", "drift", False, "RTU"), ("cdlg", "drift", True, "RTU"),
    ("ostovar3", "drift", False, "overclaim"), ("ostovar5", "drift", False, "overclaim"),
    ("null_ostovar3", "null", False, "insufficient"), ("null_ostovar5", "null", False, "insufficient"),
    ("null_cdlg", "null", False, "insufficient"),
    ("e4a", "drift", False, "time_detected"), ("e4a", "null", False, "insufficient"),
    ("e4b", "drift", False, "target_claimed"), ("e4b", "drift", False, "target_main"),
]


def majority(runs: list[dict], s: str, kind: str, roles: bool, metric: str, types=None) -> dict:
    out = {}
    ids = set.intersection(*[set(r) for r in runs]) if runs and all(runs) else set()
    for cid in ids:
        rows = [r[cid] for r in runs]
        if not roles and (rows[0]["set"] != s or rows[0]["kind"] != kind):
            continue
        if types and rows[0]["type"] not in types:
            continue
        vals = [value(r, metric) for r in rows]
        if any(v is None for v in vals):
            continue
        out[cid] = sum(v >= 1.0 for v in vals) >= 2
    return out


def compare(a: dict, b: dict) -> dict | None:
    ids = sorted(set(a) & set(b))
    if not ids:
        return None
    nb = sum(a[i] and not b[i] for i in ids)
    nc = sum(b[i] and not a[i] for i in ids)
    return {"n": len(ids), "first": sum(a[i] for i in ids) / len(ids), "second": sum(b[i] for i in ids) / len(ids),
            "b": nb, "c": nc, "p": mcnemar(nb, nc)}


def main():
    rows = []
    p2 = {m: [p2_scores(m, k) for k in RUNS] for m in (GLM, DS)}
    p2r = {m: [p2_scores(m, k, True) for k in RUNS] for m in (GLM, DS)}
    for s, kind, roles, metric in TESTS:
        src = p2r if roles else p2
        r = compare(majority(src[GLM], s, kind, roles, metric), majority(src[DS], s, kind, roles, metric))
        if r:
            rows.append({"comparison": "DeepSeek vs GLM", "set": f"{s} {kind}", "metric": metric, **r})
    for exp in EXPS:
        var = [p3_scores(exp, k) for k in RUNS]
        varr = [p3_scores(exp, k, True) for k in RUNS]
        types = {"M"} if exp in ("e5_no_time", "e5_no_cf") else None
        for s, kind, roles, metric in TESTS:
            v = varr if roles else var
            if not all(v):
                continue
            a = majority(p2r[GLM] if roles else p2[GLM], s, kind, roles, metric, types)
            r = compare(a, majority(v, s, kind, roles, metric, types))
            if r:
                rows.append({"comparison": f"{exp} vs P2 (GLM)", "set": f"{s} {kind}", "metric": metric, **r})
    md = ["# P5: exact McNemar tests (majority of three runs per arm)", "",
          "Generated by experiments/p5_stats/mcnemar_all.py. First = P2 GLM; second = DeepSeek or the variant. "
          "b = success only in the first arm, c = only in the second. E5-MP (e5_no_time, e5_no_cf) on the 26 mixed "
          "E4a cases.", "",
          "| Comparison | Set | Metric | n | First | Second | b / c | p |", "|---|---|---|---|---|---|---|---|"]
    for r in rows:
        md.append(f"| {r['comparison']} | {r['set']} | {r['metric']} | {r['n']} | {r['first']:.3f} | "
                  f"{r['second']:.3f} | {r['b']} / {r['c']} | {r['p']:.2g} |")
    (OUT / "mcnemar_all.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    with (OUT / "mcnemar_all.csv").open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    print("\n".join(md))


if __name__ == "__main__":
    main()
