#!/usr/bin/env python3
"""P5: paired comparisons of the LLM interpreters with ProDrift and with the rule-based interpreter (no API calls).

For every case: LLM value = mean over runs 1-3; rule-based interpreter (run 1) and ProDrift are deterministic.
Difference = mean over cases of (LLM - other), 95% case-bootstrap CI (aggregate_runs.boot_ci, B = 5000, seed per row).
Binary outcomes (RTU; 'insufficient' on no-change pairs): exact two-sided McNemar test, the LLM outcome of a case being
the majority over its three runs (>= 2 of 3).
ProDrift is matched to the P2 Ostovar cases by (pattern, noise, change point); CDLG uses the isolated-log scores.
Also: E6 (Qwen, one run) against GLM and DeepSeek run 1 on the same 150-case sample, with CDLG on 39 changes.
Output: results/p5_stats/method_contrasts.{md,csv}
"""
from __future__ import annotations

import csv
import math
import sys
from collections import defaultdict
from pathlib import Path
from statistics import mean

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(Path(__file__).resolve().parent))
from aggregate_runs import boot_ci  # noqa: E402

P2 = ROOT / "results" / "p2_main"
E1 = ROOT / "results" / "e1_prodrift"
OUT = ROOT / "results" / "p5_stats"
PROMPT = "INTERPRET_EVIDENCE_V2_EN_R3_MP_CONC"
LLMS = {"GLM": "glm-5.3-flash", "DeepSeek": "deepseek-v4-flash"}


def read(path: Path) -> list[dict]:
    with path.open(encoding="utf-8-sig") as handle:
        return list(csv.DictReader(handle))


def f(x) -> float:
    return float(x) if x not in ("", None, "nan") else float("nan")


def mcnemar(b: int, c: int) -> float:
    n = b + c
    if n == 0:
        return 1.0
    k = min(b, c)
    p = 2 * sum(math.comb(n, i) for i in range(k + 1)) / 2 ** n
    return min(1.0, p)


def table(rows, set_name, kind, roles=False):
    """{case_id: {metric: value}} for one score file restricted to a set."""
    out = {}
    for r in rows:
        if roles:
            out[r["case_id"]] = {m: f(r[m]) for m in ("O", "MR", "PI", "RTU")}
        elif r["set"] == set_name and r["kind"] == kind:
            out[r["case_id"]] = {"O": f(r["O"]), "MR": f(r["MR"]), "PI": f(r["PI"]), "RTU": f(r["RTU"]),
                                 "insufficient": float(r["support_level"] == "insufficient")}
    return out


def llm(model: str, set_name: str, kind: str, roles=False, runs=(1, 2, 3)) -> list[dict]:
    tag = "cdlg_roles_" if roles else ""
    return [table(read(P2 / f"scores_{tag}{PROMPT}_{model}_run{k}.csv"), set_name, kind, roles) for k in runs]


def rule(set_name: str, kind: str, roles=False) -> dict:
    tag = "cdlg_roles_" if roles else ""
    return table(read(P2 / f"scores_{tag}RULE_BASELINE_V2_rule-engine-v1_run1.csv"), set_name, kind, roles)


def prodrift(set_name: str) -> dict:
    if set_name == "cdlg":
        return {r["case_id"]: {"O": f(r["O"]), "MR": f(r["MR"]), "PI": f(r["PI"]), "RTU": f(r["RTU"])}
                for r in read(E1 / "scores_cdlg_isolated.csv")}
    size = set_name[-1]
    pd = {(r["pattern"], float(r["noise"]), r["drift"]): r for r in read(E1 / "scores.csv")
          if r["size"] == size and r["split"] == "evaluation"}
    out = {}
    for c in read(P2 / "cases.csv"):
        if c["set"] == set_name and c["kind"] == "drift":
            r = pd[(c["type"], float(c["noise_pct"]), c["drift"])]
            o, mr, pi = f(r["O"]), f(r["MR"]), f(r["PI"])
            out[c["case_id"]] = {"O": o, "MR": mr, "PI": pi, "RTU": float(o == mr == pi == 1.0)}
    return out


def contrast(runs: list[dict], other: dict, metric: str) -> dict:
    ids = sorted(set(runs[0]) & set(other))
    assert all(set(ids) <= set(r) for r in runs)
    a = {i: mean(r[i][metric] for r in runs) for i in ids}
    diffs = [a[i] - other[i][metric] for i in ids]
    lo, hi = boot_ci(diffs, None)
    res = {"n": len(ids), "llm_value": mean(a.values()), "other_value": mean(other[i][metric] for i in ids),
           "diff": mean(diffs), "lo": lo, "hi": hi, "b": "", "c": "", "p": ""}
    if metric in ("RTU", "insufficient"):
        maj = {i: sum(r[i][metric] for r in runs) >= 2 for i in ids}
        b = sum(maj[i] and not other[i][metric] for i in ids)
        c = sum((not maj[i]) and bool(other[i][metric]) for i in ids)
        res.update(b=b, c=c, p=mcnemar(b, c))
    return res


def main():
    rows, md = [], ["# P5: paired comparisons with ProDrift and the rule-based interpreter", "",
                    "Generated by experiments/p5_stats/method_contrasts.py. Diff = LLM (3-run case mean) minus the other "
                    "method, 95% case bootstrap CI. McNemar (exact, two-sided) on binary outcomes with the LLM outcome "
                    "taken as the majority of three runs; b = only the LLM succeeds, c = only the other method.", "",
                    "| LLM | vs | Set | Metric | n | LLM | Other | Diff | 95% CI | b / c | McNemar p |",
                    "|---|---|---|---|---|---|---|---|---|---|---|"]
    plan = [("ostovar3", "drift", False, ("O", "MR", "PI", "RTU")),
            ("ostovar5", "drift", False, ("O", "MR", "PI", "RTU")),
            ("cdlg", "drift", True, ("O", "MR", "PI", "RTU"))]
    for name, model in LLMS.items():
        for s, kind, roles, metrics in plan:
            runs = llm(model, s, kind, roles)
            others = {"ProDrift": prodrift(s), "Rule": rule(s, kind, roles)}
            for oname, other in others.items():
                for m in metrics:
                    c = contrast(runs, other, m)
                    rows.append({"llm": name, "vs": oname, "set": s, "metric": m, **c})
        for s in ("null_ostovar3", "null_ostovar5", "null_cdlg"):
            c = contrast(llm(model, s, "null"), rule(s, "null"), "insufficient")
            rows.append({"llm": name, "vs": "Rule", "set": s, "metric": "insufficient", **c})
    for r in rows:
        p = "" if r["p"] == "" else f"{r['p']:.2g}"
        md.append(f"| {r['llm']} | {r['vs']} | {r['set']} | {r['metric']} | {r['n']} | {r['llm_value']:.3f} | "
                  f"{r['other_value']:.3f} | **{r['diff']:+.3f}** | [{r['lo']:+.3f}, {r['hi']:+.3f}] | "
                  f"{r['b']} / {r['c']} | {p} |")

    # Levels with 95% case-bootstrap CI for every method (main table of Section VII-A)
    md += ["", "## Levels per method (mean, 95% case bootstrap CI)", "",
           "| Set | Method | O | MR | PI | RTU |", "|---|---|---|---|---|---|"]
    for s, kind, roles, metrics in plan:
        methods = {n: llm(m, s, kind, roles) for n, m in LLMS.items()}
        methods.update({"ProDrift": [prodrift(s)], "Rule": [rule(s, kind, roles)]})
        for name, runs in methods.items():
            ids = sorted(runs[0])
            cells = []
            for m in metrics:
                vals = [mean(r[i][m] for r in runs) for i in ids]
                lo, hi = boot_ci(vals, None)
                cells.append(f"{mean(vals):.3f} [{lo:.3f}, {hi:.3f}]")
            md.append(f"| {s} | {name} (n = {len(ids)}) | " + " | ".join(cells) + " |")

    # E6: Qwen run 1 vs GLM / DeepSeek run 1 on the 150-case sample
    sample = set((ROOT / "experiments" / "p2_main" / "e6_qwen_sample_cases.txt").read_text().split())
    md += ["", "## E6: Qwen (run 1) vs GLM and DeepSeek (run 1) on the 150-case sample", "",
           "| Model | Ostovar 3: O / MR / PI / RTU | CDLG roles: n, O / MR / PI / RTU | Null Ostovar 3 insufficient | "
           "Null CDLG insufficient |", "|---|---|---|---|---|"]
    for name, model in (("GLM", "glm-5.3-flash"), ("DeepSeek", "deepseek-v4-flash"),
                        ("Qwen", "qwen3.8-27b-uncensored")):
        o3 = {i: v for i, v in llm(model, "ostovar3", "drift", runs=(1,))[0].items() if i in sample}
        cd = {i: v for i, v in llm(model, "cdlg", "drift", True, runs=(1,))[0].items() if i in sample}
        n3 = {i: v for i, v in llm(model, "null_ostovar3", "null", runs=(1,))[0].items() if i in sample}
        nc = {i: v for i, v in llm(model, "null_cdlg", "null", runs=(1,))[0].items() if i in sample}
        fmt = lambda d: " / ".join(f"{mean(v[m] for v in d.values()):.3f}" for m in ("O", "MR", "PI", "RTU"))
        md.append(f"| {name} | {fmt(o3)} | {len(cd)}, {fmt(cd)} | {sum(v['insufficient'] for v in n3.values()):.0f}"
                  f"/{len(n3)} | {sum(v['insufficient'] for v in nc.values()):.0f}/{len(nc)} |")
    (OUT / "method_contrasts.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    with (OUT / "method_contrasts.csv").open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    print("\n".join(md))


if __name__ == "__main__":
    main()
